#include <iostream>
#include <string>
using namespace std;
int main() {
    int a = 10;
    double b = 3.14;
    float f = 3.14;
    char c = 'A';
    string d = "Hello, C++!";
    cout << "Integer: " << a << endl;
    cout << "Double: " << b << endl;
    cout << "Float: " << f << endl;
    cout << "Character: " << c << endl;
    cout << "String: " << d << endl;
    return 0;
}